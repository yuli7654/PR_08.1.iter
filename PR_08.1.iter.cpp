// Дано літерний рядок, який містить послідовність символів
// s[0], ..., s[n], ...
// 1. Вияснити, чи є в цій послідовності такі елементи s[i–1] , s[i+1]
// що s[i–1] – це кома (','), а s[i+1] – тире ('-'),
// та обчислити їх кількість.
// 2. Замінити кожну групу символів s[i–1] , s[i] , s[i+1] – таких, що
// s[i–1] – це кома (','), а s[i+1] – тире ('-') парою зірочок "**".

#ifndef _CRT_SECURE_NO_WARNINGS
#define _CRT_SECURE_NO_WARNINGS
#endif
#ifdef _MSC_VER
#pragma warning(disable : 4996)
#endif
#include <cstring>
#include <iostream>
using namespace std;

// Count – обчислює кількість груп s[i-1], s[i], s[i+1], у яких
//         s[i-1] == ',' та s[i+1] == '-' (символ s[i] – будь-який).
// str   – літерний рядок (функція його не змінює).
// Повертає кількість груп; 0 означає, що таких елементів у рядку немає.
int Count(char* str)
{
    // у рядку з менш ніж трьох символів групи існувати не може
    if (strlen(str) < 3)
        return 0;

    int k = 0;  // k – лічильник знайдених груп

    // i – позиція СЕРЕДНЬОГО символу групи. Починаємо з i = 1, бо потрібен
    // s[i-1]. Цикл триває, доки існує s[i+1], тобто він не нуль-символ.
    for (int i = 1; str[i + 1] != 0; i++)
        if (str[i - 1] == ',' && str[i + 1] == '-')  // кома, будь-який, тире
            k++;

    return k;
}

// Change – замінює кожну групу ',' <будь-який символ> '-' парою "**".
// str    – літерний рядок: результат повертається і через цей параметр
//          (він змінюється), і як значення функції.
// Повертає вказівник на новий рядок tmp (пам'ять виділена через new[]);
// якщо в рядку менше 3 символів, групи неможливі, і повертається сам str.
char* Change(char* str)
{
    size_t len = strlen(str);  // len – довжина вхідного рядка
    if (len < 3)
        return str;

    // Групу з 3 символів замінюємо на 2 зірочки, тож результат не довший
    // за вхідний рядок. +1 – місце для нуль-символу.
    char* tmp = new char[len + 1];
    // t – вказівник на кінець уже сформованої частини рядка tmp
    char* t = tmp;
    tmp[0] = '\0';  // спочатку tmp – порожній рядок
    // i – позиція поточного символу у вхідному рядку str
    size_t i = 0;

    // i + 2 < len – лишилося щонайменше три символи s[i], s[i+1], s[i+2]
    while (i + 2 < len)
    {
        if (str[i] == ',' && str[i + 2] == '-')  // знайдено групу
        {
            // дописуємо дві зірочки (strcat сама ставить нуль-символ)
            strcat(t, "**");
            t += 2;  // t – на кінець щойно дописаних зірочок
            i += 3;  // пропускаємо всю групу з трьох символів
        }
        else
        {
            // групи немає – копіюємо поточний символ без змін
            *t++ = str[i++];
            *t = '\0';  // підтримуємо нуль-символ у кінці tmp
        }
    }
    // «хвіст» – 0, 1 або 2 останні символи, які групи не утворюють
    while (i < len)
        *t++ = str[i++];
    *t = '\0';

    strcpy(str, tmp);  // результат повертаємо через параметр str
    return tmp;        // ... і як значення функції
}

int main()
{
    char str[101];
    cout << "Enter string:" << endl;
    cin.getline(str, 100);

    cout << "String contained " << Count(str) << " groups of ', -'" << endl;

    char* dest = new char[151];
    dest = Change(str);
    cout << "Modified string (param) : " << str << endl;
    cout << "Modified string (result): " << dest << endl;
    return 0;
}